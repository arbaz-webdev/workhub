import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { Injectable, OnModuleInit } from '@nestjs/common';
import { createReadStream, existsSync } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';
import { config } from '../config';

export interface StoredFile {
  key: string;
  contentType: string;
}

/** Either a stream to send back ourselves (local disk) or a short-lived URL to redirect to (S3/R2). */
export type Download = { kind: 'stream'; stream: Readable } | { kind: 'redirect'; url: string };

/**
 * File storage behind one interface:
 * - "local" keeps files on disk (development and tests);
 * - "s3" uses any S3-compatible service (AWS S3, Cloudflare R2), and downloads
 *   are 5-minute presigned URLs so files never pass through the API twice.
 */
@Injectable()
export class StorageService implements OnModuleInit {
  private s3?: S3Client;

  onModuleInit() {
    if (config.isProduction && config.storage.driver === 'local') {
      throw new Error('STORAGE_DRIVER=local is not allowed in production; configure S3 or R2.');
    }
    if (config.storage.driver === 's3') {
      const s = config.storage;
      this.s3 = new S3Client({
        region: s.region,
        endpoint: s.endpoint || undefined,
        forcePathStyle: !!s.endpoint,
        credentials: { accessKeyId: s.accessKeyId, secretAccessKey: s.secretAccessKey },
      });
    }
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    if (this.s3) {
      await this.s3.send(new PutObjectCommand({ Bucket: config.storage.bucket, Key: key, Body: body, ContentType: contentType }));
      return;
    }
    const path = this.localPath(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
  }

  async download(key: string, opts: { fileName: string; contentType: string; inline: boolean }): Promise<Download> {
    if (this.s3) {
      const url = await getSignedUrl(
        this.s3,
        new GetObjectCommand({
          Bucket: config.storage.bucket,
          Key: key,
          ResponseContentType: opts.contentType,
          ResponseContentDisposition: contentDisposition(opts.fileName, opts.inline),
        }),
        { expiresIn: 300 },
      );
      return { kind: 'redirect', url };
    }
    const path = this.localPath(key);
    if (!existsSync(path)) throw new Error('File missing from storage');
    return { kind: 'stream', stream: createReadStream(path) };
  }

  async delete(key: string): Promise<void> {
    if (this.s3) {
      await this.s3.send(new DeleteObjectCommand({ Bucket: config.storage.bucket, Key: key }));
      return;
    }
    await rm(this.localPath(key), { force: true });
  }

  /** Keys are generated by us, but never let one escape the storage directory. */
  private localPath(key: string) {
    const root = resolve(config.storage.localDir);
    const path = resolve(join(root, key));
    if (!path.startsWith(root + sep)) throw new Error('Invalid storage key');
    return path;
  }
}

/** RFC 6266 header with an ASCII fallback and the exact UTF-8 name (Urdu file names survive). */
export function contentDisposition(fileName: string, inline: boolean) {
  const ascii = fileName.replace(/[^\x20-\x7e]/g, '_').replace(/["\\]/g, '_');
  return `${inline ? 'inline' : 'attachment'}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`;
}
